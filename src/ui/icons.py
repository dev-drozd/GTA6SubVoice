_ICON_CACHE: dict[tuple[str, str, int, float], QIcon] = {}


def make_svg_pixmap(name: str, color: str = "#F4F3FA", size: int = 16, stroke_width: float = 1.9) -> QPixmap:
    """Рендерит чёткий векторный SVG-пиксмап в HiDPI (2x)."""
    body = _SVG_PATHS.get(name, _SVG_PATHS["sparkles"])
    svg_xml = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round" color="{color}">'
        f"{body}</svg>"
    )
    dpr = 2.0
    px_size = int(round(size * dpr))
    pm = QPixmap(px_size, px_size)
    pm.fill(Qt.GlobalColor.transparent)
    pm.setDevicePixelRatio(dpr)

    renderer = QSvgRenderer(QByteArray(svg_xml.encode("utf-8")))
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    # Небольшой вертикальный оптический сдвиг +0.6px выравнивает иконки по высоте заглавных букв шрифтов
    renderer.render(painter, QRectF(0.0, 0.6, float(size), float(size)))
    painter.end()
    return pm


def svg_icon(name: str, color: str = "#F4F3FA", size: int = 16, stroke_width: float = 1.9) -> QIcon:
    """Возвращает кэшированную HiDPI-иконку QIcon."""
    key = (name, color, size, stroke_width)
    cached = _ICON_CACHE.get(key)
    if cached is not None:
        return cached
    icon = QIcon(make_svg_pixmap(name, color=color, size=size, stroke_width=stroke_width))
    _ICON_CACHE[key] = icon
    return icon
